-- V20: защита от повторного использования TOTP-кода (S44)
--
-- validateCurrentNumber принимает окно ±1 шаг (30 секунд), поэтому один и тот
-- шестизначный код можно было предъявлять многократно, пока шаг не сменился.
-- Храним номер последнего принятого шага и отклоняем всё, что не новее.

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS totp_last_counter BIGINT;
